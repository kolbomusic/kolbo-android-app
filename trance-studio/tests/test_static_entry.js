'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path='trance-studio/entry/index.html';
const shell=fs.readFileSync(path,'utf8');
assert.match(shell,/<html lang="he" dir="rtl">/);
assert.match(shell,/href="https:\/\/kolbo-trance-studio\.onrender\.com\/studio"/);
assert.match(shell,/fetch\(SERVER\+'\/health\?gateway=1'/);
assert.match(shell,/health\.ok!==true/);
assert.match(shell,/aria-disabled="true"/);
assert.match(shell,/window\.location\.assign\(STUDIO\)/);
const script=shell.split('<script>')[1]?.split('</script>')[0];
assert.ok(script,'Inline JS script exists');
new Function(script);
const neverAutoCreate = /\/api\/jobs|\.click\(\)|generate\s*\(/;
assert.doesNotMatch(script,neverAutoCreate,'Gateway must not auto-start media creation');
const safeConnection = /AbortController|MAX_ATTEMPTS|cache:'no-store'/;
assert.match(script,safeConnection);
console.log('STATIC_GATEWAY_LOADS_INSTANTLY_AND_ONLY_REDIRECTS_AFTER_HEALTH_PASS');
